namespace PergamonLens.Domain.Enums;

/// <summary>
/// Velocidad de rotación estándar del disco de vinilo en revoluciones por minuto (RPM).
/// </summary>
public enum VinylSpeed
{
    Rpm33 = 1, // 33 ⅓ RPM (LPs estándar)
    Rpm45 = 2, // 45 RPM (Singles y Maxis de audiófilo)
    Rpm78 = 3  // 78 RPM (Discos históricos de pizarra/goma laca)
}

